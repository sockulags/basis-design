import { COLOR_ROLES, componentTokens, globalTokenGroups, kebab, type Design } from "./design.ts";

/**
 * Maps a design document to CSS custom properties. The JSON path → variable
 * rules here (with design.ts, which also checks that no two tokens share a
 * variable) are the contract described to the agent in its brief.
 */

export { kebab };

export type CssVar = readonly [name: string, value: string];

function entries(prefix: string, record: Record<string, string>): CssVar[] {
  return Object.entries(record).map(([key, value]) => [`--${prefix}-${kebab(key)}`, value] as const);
}

export function colorVars(design: Design, theme: "light" | "dark"): CssVar[] {
  const set = design.color[theme];
  return COLOR_ROLES.map((role) => [`--color-${kebab(role)}`, set[role]] as const);
}

/** Theme-independent variables: typography, space, shape, motion, and the tokens of every component. */
export function baseVars(design: Design): CssVar[] {
  return [
    ...globalTokenGroups(design).flatMap(([prefix, tokens]) => entries(prefix, tokens)),
    ...componentTokens(design).map((token) => [token.cssVar, token.value] as const),
  ];
}

function block(selector: string, vars: CssVar[], indent = ""): string {
  const body = vars.map(([name, value]) => `${indent}  ${name}: ${value};`).join("\n");
  return `${indent}${selector} {\n${body}\n${indent}}`;
}

/** Scoped stylesheet for the live preview. Light is the default; dark applies under data-theme="dark". */
export function previewCss(design: Design, scope: string): string {
  return [
    block(scope, [...baseVars(design), ...colorVars(design, "light")]),
    block(`${scope}[data-theme="dark"]`, colorVars(design, "dark")),
  ].join("\n\n");
}

function fontImports(design: Design): string {
  return design.typography.fontImports.map((url) => `@import url("${url}");`).join("\n");
}

function header(design: Design, kind: string): string {
  return `/* ${design.name} — ${kind}, generated by Basis */`;
}

/** Standalone tokens.css: light by default, dark via data-theme or the OS preference. */
export function exportCss(design: Design): string {
  const imports = fontImports(design);
  return [
    header(design, "design tokens"),
    imports,
    block(":root", [...baseVars(design), ...colorVars(design, "light")]),
    block('[data-theme="dark"]', colorVars(design, "dark")),
    `@media (prefers-color-scheme: dark) {\n${block(':root:not([data-theme="light"])', colorVars(design, "dark"), "  ")}\n}`,
  ]
    .filter(Boolean)
    .join("\n\n")
    .concat("\n");
}

/**
 * Tailwind v4 entry stylesheet. Names that coincide with Tailwind's theme
 * namespaces (color, font, text, leading, tracking, radius, shadow, ease) go
 * into @theme so utilities like bg-primary or rounded-md use them directly.
 */
export function exportTailwind(design: Design): string {
  const type = design.typography;
  const theme: CssVar[] = [
    ["--color-*", "initial"],
    ...colorVars(design, "light"),
    ...entries("font", type.family),
    ...entries("text", type.size),
    ...entries("font-weight", type.weight),
    ...entries("leading", type.leading),
    ...entries("tracking", type.tracking),
    ...entries("radius", design.radius),
    ...entries("shadow", design.shadow),
    ...entries("ease", design.motion.ease),
    ["--spacing", design.space["1"]],
  ];
  const themeNames = new Set(theme.map(([name]) => name));
  const extra = baseVars(design).filter(([name]) => !themeNames.has(name));
  return [
    header(design, "Tailwind v4 theme"),
    [fontImports(design), '@import "tailwindcss";'].filter(Boolean).join("\n"),
    '@custom-variant dark (&:where([data-theme="dark"], [data-theme="dark"] *));',
    block("@theme", theme),
    block(":root", extra),
    block('[data-theme="dark"]', colorVars(design, "dark")),
  ]
    .join("\n\n")
    .concat("\n");
}

export function exportJson(design: Design): string {
  return `${JSON.stringify(design, null, 2)}\n`;
}
