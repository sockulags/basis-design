import { KIT_FOLDER } from "../shared/capture.ts";

/*
 * The verification kit's texts for the agent that builds the design in the product: PROMPT.md (the goal, the
 * views and how to work), SKILL.md (the same loop as a Claude Code skill) and a paragraph for AGENTS.md in the
 * README. The loop, the rules for images and exceptions and when to stop are written once, here, and shared by
 * PROMPT.md and SKILL.md. Paths are relative to the product repo's root, where the kit is `kit` (`basis-verify/`
 * unless another folder was chosen).
 */

/** Where Claude Code finds the skill in the product repo, when Basis installs it there. */
export const SKILL_PATH = ".claude/skills/basis-verify/SKILL.md";
/** The line that marks a SKILL.md as Basis' own: Basis replaces an installed skill only when it has this. */
export const SKILL_MARKER = "<!-- Generated by Basis.";

/** A view as PROMPT.md lists it. */
export interface PromptView {
  id: string;
  title: string;
  screens: { id: string; label: string }[];
}

/** The loop, the rules for images and exceptions, and when to stop: shared by PROMPT.md and SKILL.md. */
function loop(example: { view: string; screen: string }, kit: string): string {
  const one = `${example.view}/${example.screen}`;
  return `## The loop

Once per machine: the scripts need Node 22 and Playwright in the product (\`npm i -D playwright\`, then
\`npx playwright install chromium\`). Use the product's Playwright if it has one.

1. Capture the design on this machine. Fonts and antialiasing differ between systems, so only images taken here
   with the same browser can match; \`${kit}/screens/\` is the reference only when nothing else is there.

   \`\`\`bash
   node ${kit}/capture.mjs design --only <view>
   \`\`\`

2. Point each screen at its page in the product: copy \`${kit}/targets.example.json\` to \`${kit}/targets.json\`,
   set \`baseUrl\` to the product's dev server and each \`"<view>/<screen>"\` to the path of its page. An entry may be
   \`{ "url": "/team/42", "waitFor": "[data-loaded]" }\` to wait for an element first. Add
   \`"themeAttribute": "data-theme"\` when the product switches themes with an attribute on \`<html>\`, and
   \`"storageState": "auth.json"\` (a Playwright storage state) for pages behind a login.

3. Start the product's dev server, leave it running, and capture the implementation:

   \`\`\`bash
   node ${kit}/capture.mjs app --only <view>/<screen>
   \`\`\`

4. Compare:

   \`\`\`bash
   node ${kit}/compare.mjs --only <view>/<screen>
   \`\`\`

   Each shot prints PASS, FAIL (with the share of pixels that differ, and what is wrong with the images left out),
   MISSING or EXCEPTED. The command exits with 1 while any shot fails or is missing.

5. Read the diffs. \`${kit}/diff/<view>/<screen>@<width>.png\` shows matching pixels faded, differing pixels red
   and left-out parts blue; \`${kit}/diff/report.json\` has the numbers and both images' sizes. Look at the
   design's image (\`${kit}/expected/…\`) and the product's (\`${kit}/actual/…\`) to see what is wrong: spacing,
   a size, the font, a colour, a line that wraps. "size 375x1210, expected 375x1180" means the page is taller or
   shorter than the design; fix that before the details, since everything below it moves.

6. Fix the implementation and go back to step 3. Capture the design again only when the kit has changed.

\`--only\` takes a view (\`${example.view}\`) or one of its screens (\`${one}\`); without it the scripts take every
shot in the kit.

## Images and exceptions

- Photos, avatars and illustrations cannot match pixel for pixel. The design marks them with \`data-basis-media\`
  and shows placeholders; mark the element that takes each one's place in the product the same way
  (\`<img data-basis-media src={user.photo} alt="…">\`). \`compare.mjs\` leaves those elements out of every shot, but
  checks that both sides have as many of them, each at the same place and with the same size, to the pixel. A
  missing, moved or resized image still fails.
- Anything else may differ only as a named exception in \`${kit}/exceptions.json\` (start from
  \`exceptions.example.json\`): a \`name\`, a \`reason\` a reviewer can check, the \`view\`, optionally \`screen\`,
  \`widths\` and \`themes\`, and a \`selector\` (\`"canvas"\`, or \`{ "design": "…", "app": "…" }\` when the two sides
  need different ones) or a \`region\` in the image's pixels. A selector's elements are checked like images: same
  number, place and size. Capture both sides again after adding a selector.
- Add an exception only for something that cannot be the same for a reason you can name: a live chart, data only
  the product has, an embed from another service. Never for layout, spacing, text or colour you have not got
  right yet. Every exception you add goes in your report.

## When you are done, and when to stop

- Done: every shot of the screens you were asked to build prints PASS or EXCEPTED.
- The target is 0% difference. Basis has not set a tolerance, so do not pass \`--max-diff\`, \`--tolerance\` or
  \`--box-tolerance\` unless the person who asked you says so.
- Stop and report instead of going on when:
  - three rounds in a row have not lowered a shot's differing pixels;
  - what is left needs a change outside the view, such as a shared component, global styles, the product's tokens
    or a font the product does not load: that changes other pages, so say what it is and leave the decision to
    the person who asked you;
  - a screen has no URL in the product, or its data cannot be shown on the page;
  - \`capture.mjs\` reports a shot as UNSTABLE: the page renders differently each time (a clock, a random value,
    an animation, content that arrives late). Fix it in the product if it is yours to fix, else report it.
- Report, for each shot, its status and percentage from \`compare.mjs\`, what you changed, the exceptions you
  added and why, and what is left with its cause.
`;
}

function example(views: PromptView[]): { view: string; screen: string } {
  return { view: views[0]?.id ?? "<view>", screen: views[0]?.screens[0]?.id ?? "<screen>" };
}

/** `PROMPT.md`: the goal, where things are in the kit, the views with pointers to their notes, and the loop. */
export function promptFile(
  designSystem: string,
  generator: string,
  views: PromptView[],
  kit: string = KIT_FOLDER,
): string {
  const rows = views.map(
    (view) =>
      `| ${view.title} (\`${view.id}\`) | ${view.screens.map((screen) => `\`${screen.id}\` ${screen.label}`).join(", ")} | \`${kit}/views/${view.id}.md\` |`,
  );
  return `# Build the design in this product: ${designSystem}

Written by ${generator} for the agent that builds these views in the product. Paths are relative to the root of
the product's repo, where this kit is the folder \`${kit}/\`.

## The goal

Build the views below in this product so that each of their screens looks like the design: the same layout, text,
sizes and colours, checked pixel for pixel at the sizes the kit lists. Build them with the product's own code: its
components, styles, tokens, routes and data. The design's source shows what to build; it is not code to copy into
the product. Build only the views or screens you were asked for.

## Where things are

- \`${kit}/PROMPT.md\`: this file.
- \`${kit}/views/<view>.md\`: the notes for each view: its screens and their shots, where each screen leads, the
  components, patterns and data it uses, and the design's tokens it reads with their values.
- \`${kit}/source/\`: the design's source of the views and of everything they use (React and CSS modules).
- \`${kit}/screens/\`: the screenshots Basis took, \`<view>/<screen>@<width>[x<height>][-dark].png\`.
- \`${kit}/design/\`: the design as a static site, which \`capture.mjs\` serves.
- \`${kit}/basis-verify.json\`: every shot and the settings it was taken with.
- \`${kit}/capture.mjs\` and \`${kit}/compare.mjs\`: the scripts of the loop below.
- \`${kit}/targets.example.json\` and \`${kit}/exceptions.example.json\`: starting points for your
  \`targets.json\` and \`exceptions.json\`, which Basis never replaces.
- \`${kit}/README.md\`: the same kit described for people, with every option of the scripts.

## The views

| View | Screens | Notes |
| --- | --- | --- |
${rows.join("\n") || "| (none) | | |"}

## How to build a view

1. Read the view's notes and its source in \`${kit}/source/\`, and look at its screenshots in \`${kit}/screens/\`.
2. Find where it belongs in the product: the route or page that shows that part of the product, and the
   product's components and tokens for what the view uses. Prefer what the product has to anything new.
3. Give each screen you build a URL the product's dev server answers: its route, or the query or state the
   product already uses for it (a dialog the product opens from a URL, say). The kit captures pages by URL only.
4. While you verify, the page must show the design's data (in the view's source). Use the product's own seed
   data, fixtures or mocks for that, never constants in the shipped code.
5. Work in the loop below until every shot of those screens passes, or until a reason to stop comes up.

${loop(example(views), kit)}`;
}

/** `SKILL.md`: the loop as a Claude Code skill, in the kit and, when asked, in the product's `.claude/skills/`. */
export function skillFile(views: PromptView[], folder: string = KIT_FOLDER): string {
  // Kits in folders of their own under basis-verify/ (one per view or issue) share one skill, which names none.
  const root = folder.split("/")[0]!;
  const nested = folder !== root;
  const kit = nested ? `${root}/<kit>` : folder;
  const where = nested
    ? `Each verification kit is a folder under \`${root}/\` at the root of the repo, named for its view or issue (\`${folder}/\` is one). Use the kit of what you build, written \`${kit}/\` below, and read its \`PROMPT.md\` first: the goal, the views and how to build one. Each view's notes are in \`${kit}/views/<view>.md\`.`
    : `The kit is in \`${kit}/\` at the root of the repo. Read \`${kit}/PROMPT.md\` first: the goal, the views and how
to build one. Each view's notes are in \`${kit}/views/<view>.md\`.`;
  return `---
name: basis-verify
description: "Build or check a screen designed in Basis against the verification kit in ${kit}/. Captures the design and the implementation, compares them pixel for pixel, reads the diffs and fixes until they match. Use when implementing a view from ${kit}/, or when asked to verify a page against the Basis design."
---

${SKILL_MARKER} Basis replaces this file when it writes the verification kit again; delete this line to keep your own version. -->

# Build and verify against the Basis design

${where}

${loop(example(views), kit)}`;
}

/** The same instructions as one paragraph, for a product whose agents read AGENTS.md rather than skills. */
export function agentsParagraph(kit: string = KIT_FOLDER): string {
  return `To build a view from the Basis design, read \`${kit}/PROMPT.md\` and the view's notes in \`${kit}/views/\`.
Capture the design with \`node ${kit}/capture.mjs design --only <view>\`, build the screens with the product's
own components and tokens, point \`${kit}/targets.json\` at their pages, capture them with
\`node ${kit}/capture.mjs app --only <view>/<screen>\` and compare with \`node ${kit}/compare.mjs --only <view>/<screen>\`.
Read the diff images in \`${kit}/diff/\`, fix and repeat until every shot passes. Only elements marked
\`data-basis-media\` and named exceptions in \`${kit}/exceptions.json\`, each with a reason, may differ; the target is
0% with no tolerance. Stop and report when three rounds bring no progress, or when a fix would change shared code,
global styles or the product's tokens.`;
}
