import { existsSync } from "node:fs";
import { mkdir, readFile, readdir, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { strToU8, zipSync } from "fflate";
import type { Design } from "../shared/design.ts";
import type { ExportFile, ExportWriteResult } from "../shared/protocol.ts";
import { exportCss, exportJson, exportTailwind } from "../shared/tokens.ts";

const repoRoot = path.resolve(import.meta.dirname, "..");

export function slug(name: string): string {
  return (
    name
      .toLowerCase()
      .normalize("NFKD")
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "") || "design-system"
  );
}

/**
 * Workspace code imports siblings with explicit extensions ("./util.ts"),
 * which needs a TypeScript flag most projects do not set. Exported code uses
 * extensionless relative imports, which every bundler resolves.
 */
function stripImportExtensions(source: string): string {
  return source.replace(/(\bfrom\s+|\bimport\s*\(\s*|\bimport\s+)(["'])(\.{1,2}\/[^"']+?)\.(tsx?|jsx?)\2/g, "$1$2$3$2");
}

function readme(design: Design, components: string[]): string {
  const families = components
    .filter((file) => /\.tsx$/.test(file) && !file.includes(".specimen."))
    .map((file) => `- \`components/${file}\``)
    .join("\n");
  return `# ${design.name}

${design.description || "A design system generated with Basis."}

## Contents

- \`tokens.css\`: every design token as a CSS custom property. Light by default, dark under
  \`data-theme="dark"\` or the operating system's dark preference. Font imports are included.
- \`theme.tailwind.css\`: the same tokens as a Tailwind v4 entry stylesheet, for Tailwind projects.
- \`design-system.json\`: the source tokens, for tooling or for importing back into Basis.
- \`components/\`: React components styled with CSS Modules and the token variables. The
  \`*.specimen.tsx\` files describe every component in every state; they are living documentation and
  a ready-made source for stories or visual tests, and nothing imports them by default.

${families}

## Use it

1. Copy this folder into your project, for example as \`src/design-system/\`.
2. Load the tokens once, at the root of the app:
   - without Tailwind: \`import "./design-system/tokens.css";\`
   - with Tailwind v4: use \`theme.tailwind.css\` as the app's main stylesheet instead of \`@import "tailwindcss"\`.
     Utilities such as \`bg-primary\`, \`text-text-muted\` and \`rounded-md\` then use the design tokens.
3. Use the components:

   \`\`\`tsx
   import { Button, Field, TextInput } from "./design-system/components";

   <Field label="Email">
     <TextInput placeholder="name@company.com" />
   </Field>
   <Button variant="primary">Continue</Button>
   \`\`\`

4. For dark mode, set \`data-theme="dark"\` (or \`"light"\`) on \`<html>\`, or leave it unset to follow the OS.

Requirements: React 18 or newer and a bundler with CSS Modules support (Vite, Next.js, Remix and
webpack's css-loader all qualify). The components have no other dependencies.

The \`data-ds\`, \`data-force\` and \`force\` hooks exist so the Basis gallery can show every state at once.
They are harmless in an app, and \`force\` is handy in your own stories or visual tests.

Generated by Basis on ${new Date().toISOString().slice(0, 10)}.
`;
}

/** Everything a new project needs: components, tokens in three forms, and a README. */
export async function buildStarterKit(design: Design, componentsDir: string): Promise<ExportFile[]> {
  const entries = (await readdir(componentsDir, { recursive: true })).map((entry) => entry.split(path.sep).join("/"));
  const components: string[] = [];
  const files: ExportFile[] = [];
  for (const entry of entries.sort()) {
    const full = path.join(componentsDir, entry);
    if (!(await stat(full)).isFile()) continue;
    let content = await readFile(full, "utf8");
    if (/\.(tsx?|jsx?)$/.test(entry)) content = stripImportExtensions(content);
    // The workspace's index.ts talks about the Basis gallery; in a project it is just the public entry point.
    if (entry === "index.ts") content = content.replace(/^\/\/ Every component the Basis gallery renders\..*\n/, "// Public entry point of the design system's components.\n");
    components.push(entry);
    files.push({ path: `components/${entry}`, content });
  }
  return [
    { path: "README.md", content: readme(design, components) },
    { path: "tokens.css", content: exportCss(design) },
    { path: "theme.tailwind.css", content: exportTailwind(design) },
    { path: "design-system.json", content: exportJson(design) },
    ...files,
  ];
}

/** Re-exporting an unchanged kit only differs in the README's date line; that is not a conflict. */
function withoutStamp(text: string): string {
  return text.replace(/^Generated by Basis on .*$/m, "");
}

export function zipStarterKit(files: ExportFile[], folder: string): Uint8Array {
  return zipSync(Object.fromEntries(files.map((file) => [`${folder}/${file.path}`, strToU8(file.content)])), { level: 6 });
}

/**
 * Writes the kit into a folder of the user's choosing. Refuses to touch Basis
 * itself, and reports files that would change instead of overwriting them
 * unless the user confirmed.
 */
export async function writeStarterKit(
  files: ExportFile[],
  target: string,
  overwrite: boolean,
): Promise<ExportWriteResult> {
  const trimmed = target.trim();
  if (!trimmed || !path.isAbsolute(trimmed)) {
    return { ok: false, target: trimmed, written: [], conflicts: [], error: "Enter an absolute folder path." };
  }
  const dir = path.resolve(trimmed);
  const relativeToBasis = path.relative(repoRoot, dir);
  if (!relativeToBasis.startsWith("..") && !path.isAbsolute(relativeToBasis)) {
    return { ok: false, target: dir, written: [], conflicts: [], error: "That folder is inside Basis itself. Pick a folder in your project." };
  }
  const conflicts: string[] = [];
  for (const file of files) {
    const destination = path.join(dir, file.path);
    if (!existsSync(destination)) continue;
    const current = await readFile(destination, "utf8").catch(() => null);
    if (current === null || withoutStamp(current) !== withoutStamp(file.content)) conflicts.push(file.path);
  }
  if (conflicts.length && !overwrite) return { ok: false, target: dir, written: [], conflicts };
  const written: string[] = [];
  for (const file of files) {
    const destination = path.join(dir, file.path);
    await mkdir(path.dirname(destination), { recursive: true });
    await writeFile(destination, file.content);
    written.push(file.path);
  }
  return { ok: true, target: dir, written, conflicts: [] };
}
